// Self-hosts the frame studio's fonts (src/studio/fonts/registry.js):
//   - woff2 files               → public/fonts/studio/
//   - @font-face rules           → src/studio/fonts/studio-fonts.css
// The fonts are open-license (OFL) Google Fonts, taken from their @fontsource packages with
// `npm pack` into a temp folder, so nothing is added to package.json.
// Run: node scripts/studio/gen-fonts.mjs   (needs the npm registry)
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { FONTS } from '../../src/studio/fonts/registry.js';

const FONTSOURCE_VERSION = '5.3.0';
const OUT_DIR = 'public/fonts/studio';
const CSS_FILE = 'src/studio/fonts/studio-fonts.css';

const temp = mkdtempSync(join(tmpdir(), 'studio-fonts-'));
const rules = ['/* Generated by scripts/studio/gen-fonts.mjs from src/studio/fonts/registry.js. Do not edit by hand. */'];
let files = 0;
try {
  rmSync(OUT_DIR, { recursive: true, force: true });
  mkdirSync(OUT_DIR, { recursive: true });
  for (const font of FONTS) {
    const dir = join(temp, font.pkg);
    mkdirSync(dir);
    const spec = `@fontsource/${font.pkg}@${FONTSOURCE_VERSION}`;
    const tgz = execFileSync('npm', ['pack', spec, '--silent'], { cwd: dir, encoding: 'utf8' }).trim().split('\n').pop();
    execFileSync('tar', ['-xzf', tgz], { cwd: dir });
    const pkg = join(dir, 'package');
    for (const weight of font.weights) {
      // "<weight>.css" holds every subset of the weight, each with its unicode-range.
      const css = readFileSync(join(pkg, `${weight}.css`), 'utf8');
      for (const subset of font.subsets) {
        const name = `${font.pkg}-${subset}-${weight}-normal`;
        const block = css.match(new RegExp(`/\\* ${name} \\*/\\s*@font-face \\{([^}]*)\\}`));
        if (!block) throw new Error(`${spec}: no ${subset} ${weight}`);
        if (!block[1].includes(`font-family: '${font.family}'`)) throw new Error(`${spec}: family is not '${font.family}'`);
        const range = /unicode-range: ([^;]+);/.exec(block[1])?.[1];
        copyFileSync(join(pkg, 'files', `${name}.woff2`), join(OUT_DIR, `${name}.woff2`));
        files += 1;
        rules.push(
          `@font-face { font-family: '${font.family}'; font-style: normal; font-display: swap; font-weight: ${weight};` +
            ` src: url('/fonts/studio/${name}.woff2') format('woff2');${range ? ` unicode-range: ${range};` : ''} }`,
        );
      }
    }
  }
} finally {
  rmSync(temp, { recursive: true, force: true });
}
writeFileSync(CSS_FILE, `${rules.join('\n')}\n`);
console.warn(`${files} font files for ${FONTS.length} families → ${OUT_DIR}, ${CSS_FILE}`);
