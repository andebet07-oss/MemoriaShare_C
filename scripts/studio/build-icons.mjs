// Writes the artwork for src/studio/icons/catalog.js:
//   - single-colour paths (Phosphor, MingCute, custom rings) → src/studio/icons/symbolPaths.js
//   - Fluent Emoji SVGs                                      → public/studio/emoji/<id>.svg
// Run with `node scripts/studio/build-icons.mjs`. Needs the npm registry: the Iconify icon sets are downloaded with
// `npm pack` into a temp folder, so nothing is added to package.json.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { EMOJI, SYMBOLS } from '../../src/studio/icons/catalog.js';

const PACKAGES = {
  ph: '@iconify-json/ph@1.2.2',
  mingcute: '@iconify-json/mingcute@1.2.9',
  'fluent-emoji': '@iconify-json/fluent-emoji@1.2.7',
};
const custom = JSON.parse(readFileSync('src/studio/icons/customPaths.json', 'utf8'));

function loadSet(temp, name) {
  const spec = PACKAGES[name];
  const dir = join(temp, name);
  mkdirSync(dir);
  const tgz = execFileSync('npm', ['pack', spec, '--silent'], { cwd: dir, encoding: 'utf8' }).trim().split('\n').pop();
  execFileSync('tar', ['-xzf', tgz], { cwd: dir });
  return JSON.parse(readFileSync(join(dir, 'package', 'icons.json'), 'utf8'));
}

/** Single-colour artwork: the filled paths of an Iconify icon (other paths are invisible spacers). */
function symbolArtwork(sets, { id, src }) {
  const [set, name] = src.split(':');
  if (set === 'custom') {
    if (!custom[name]) throw new Error(`${id}: no "${name}" in customPaths.json`);
    return custom[name];
  }
  const data = sets[set];
  const icon = data?.icons[name];
  if (!icon) throw new Error(`${id}: "${src}" not found`);
  if (/stroke=|fill-rule="evenodd"|<(?!path|\/)/.test(icon.body)) throw new Error(`${id}: "${src}" is not plain filled paths`);
  const paths = [...icon.body.matchAll(/<path fill="currentColor" d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${id}: no filled path in "${src}"`);
  return { viewBox: [icon.left ?? 0, icon.top ?? 0, icon.width ?? data.width ?? 16, icon.height ?? data.height ?? 16], path: paths.join(' ') };
}

const temp = mkdtempSync(join(tmpdir(), 'icons-'));
try {
  const sets = Object.fromEntries(Object.keys(PACKAGES).map((name) => [name, loadSet(temp, name)]));

  const symbols = Object.fromEntries(SYMBOLS.map((s) => [s.id, symbolArtwork(sets, s)]));
  writeFileSync(
    'src/studio/icons/symbolPaths.js',
    `// Generated by scripts/studio/build-icons.mjs from Phosphor (MIT), MingCute (Apache-2.0) and src/studio/icons/customPaths.json.\n` +
      `// Do not edit by hand: change src/studio/icons/catalog.js and run \`npm run icons\`.\n` +
      `export const SYMBOL_PATHS = ${JSON.stringify(symbols, null, 2)};\n`,
  );
  console.warn(`symbols: ${Object.keys(symbols).length}`);

  const fluent = sets['fluent-emoji'];
  rmSync('public/studio/emoji', { recursive: true, force: true });
  mkdirSync('public/studio/emoji', { recursive: true });
  for (const { id } of EMOJI) {
    const icon = fluent.icons[id];
    if (!icon) throw new Error(`emoji "${id}" not in ${PACKAGES['fluent-emoji']}`);
    const width = icon.width ?? fluent.width ?? 32;
    const height = icon.height ?? fluent.height ?? 32;
    writeFileSync(
      `public/studio/emoji/${id}.svg`,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">${icon.body}</svg>\n`,
    );
  }
  console.warn(`emoji: ${EMOJI.length}`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
